/** Paint the land mask (white land on black sea) into a canvas, equirectangular, north at the top. */
export function drawLandMask(width = 1024, height = 512): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  const x = (lon: number) => ((lon + 180) / 360) * width;
  const y = (lat: number) => ((90 - lat) / 180) * height;
  const fill = (polys: readonly Poly[], color: string) => {
    ctx.fillStyle = color;
    for (const poly of polys) {
      ctx.beginPath();
      poly.forEach(([lon, lat], i) => (i === 0 ? ctx.moveTo(x(lon), y(lat)) : ctx.lineTo(x(lon), y(lat))));
      ctx.closePath();
      ctx.fill();
    }
  };
  ctx.fillStyle = '#000';
  ctx.fillRect(0, 0, width, height);
  fill(LAND, '#fff');
  fill(WATER, '#000');
  return canvas;
}
